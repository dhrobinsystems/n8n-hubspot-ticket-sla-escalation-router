function serialize(workflow) {
  return `${JSON.stringify(workflow, null, 2)}\n`;
}

function main(argv) {
  const args = new Set(argv);
  const output = serialize(buildWorkflow());

  if (args.has('--stdout')) {
    process.stdout.write(output);
    return 0;
  }
  if (args.has('--check')) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
    if (current !== output) {
      console.error('workflow.json is out of date with src/. Run `npm run build` and commit the result.');
      return 1;
    }
    console.log('workflow.json is up to date.');
    return 0;
  }
  fs.writeFileSync(OUTPUT, output);
  console.log(`Wrote ${path.relative(ROOT, OUTPUT)} (${Buffer.byteLength(output)} bytes, ${buildWorkflow().nodes.length} nodes).`);
  return 0;
}

if (require.main === module) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (err) {
    console.error(`Build failed: ${err.message}`);
    process.exitCode = 1;
  }
}

module.exports = { buildWorkflow, buildPreamble, serialize, stableId, ENTRIES, CREDENTIALS };
