#!/usr/bin/env node
'use strict';

/**
 * scripts/build-workflow.js
 * ---------------------------------------------------------------------------
 * Compiles src/config.js and src/slaEngine.js into the n8n Code nodes of
 * workflow.json, so the logic that runs in n8n is exactly the logic covered
 * by the unit tests.
 *
 * Usage
 *   node scripts/build-workflow.js           # write workflow.json
 *   node scripts/build-workflow.js --check   # exit 1 if workflow.json is stale (CI)
 *   node scripts/build-workflow.js --stdout  # print instead of writing
 *
 * Every credential reference is a placeholder. After importing into n8n,
 * open each HubSpot / Slack / SMTP node and select your own credential.
 * ---------------------------------------------------------------------------
 */

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const ROOT = path.resolve(__dirname, '..');
const OUTPUT = path.join(ROOT, 'workflow.json');
const PKG = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));

const WORKFLOW_NAME = 'HubSpot Ticket SLA Escalation Router';
const HUBSPOT_API = 'https://api.hubapi.com';

/** Placeholder credentials: n8n will ask you to pick real ones after import. */
const CREDENTIALS = Object.freeze({
  hubspot: { hubspotAppToken: { id: 'REPLACE_WITH_HUBSPOT_CREDENTIAL_ID', name: 'HubSpot Private App Token (placeholder)' } },
  slack: { slackApi: { id: 'REPLACE_WITH_SLACK_CREDENTIAL_ID', name: 'Slack Bot Token (placeholder)' } },
  smtp: { smtp: { id: 'REPLACE_WITH_SMTP_CREDENTIAL_ID', name: 'SMTP Account (placeholder)' } },
});

/** Retry policy for every outbound HTTP call (covers HubSpot 429 / 5xx responses). */
const RETRY = Object.freeze({ retryOnFail: true, maxTries: 3, waitBetweenTries: 3000 });

/** Deterministic UUID-shaped node IDs keep diffs and the --check comparison stable. */
function stableId(seed) {
  const h = crypto.createHash('sha1').update(`sla-router:${seed}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

function readSource(relPath) {
  const source = fs.readFileSync(path.join(ROOT, relPath), 'utf8');
  const codeLines = source.split('\n').filter((line) => !/^\s*(\*|\/\/|\/\*)/.test(line));
  if (codeLines.some((line) => /\brequire\s*\(/.test(line))) {
    throw new Error(`${relPath} must not call require(); it is inlined into n8n Code nodes.`);
  }
  return source.trimEnd();
}

/** Shared header for every Code node: inlines both modules and safe env/execution helpers. */
function buildPreamble() {
  return [
    `// ===== AUTO-GENERATED by scripts/build-workflow.js (v${PKG.version}). Do not edit in n8n. =====`,
    '// Edit src/config.js or src/slaEngine.js, run `npm run build`, then re-import workflow.json.',
    'const __loadModule = (factory) => { const module = { exports: {} }; factory(module, module.exports); return module.exports; };',
    '',
    '// ---- src/config.js ----',
    'const Config = __loadModule(function (module, exports) {',
    readSource('src/config.js'),
    '});',
    '',
    '// ---- src/slaEngine.js ----',
    'const Engine = __loadModule(function (module, exports) {',
    readSource('src/slaEngine.js'),
    '});',
    '',
    '// ---- n8n runtime helpers ----',
    '/** Copy only known keys from $env; tolerates N8N_BLOCK_ENV_ACCESS_IN_NODE. */',
    'function __readEnv() {',
    '  const env = {};',
    '  let source;',
    '  try { source = $env; } catch (err) { source = undefined; }',
    '  if (!source) return env;',
    '  for (const key of Config.ENV_KEYS) {',
    '    try {',
    '      const value = source[key];',
    "      if (value !== undefined && value !== null && value !== '') env[key] = String(value);",
    '    } catch (err) { /* blocked or missing: fall back to defaults */ }',
    '  }',
    '  return env;',
    '}',
    'function __runId() {',
    '  try { return $execution && $execution.id ? String($execution.id) : null; } catch (err) { return null; }',
    '}',
    '',
  ].join('\n');
}

/** Node-specific entry points appended after the preamble. */
const ENTRIES = {
  buildSearch: [
    '// ===== ENTRY: Build Search Request =====',
    '// Fail fast: an invalid configuration throws here, before any HubSpot call is made.',
    'const config = Config.loadConfig(__readEnv());',
    'const searchBody = Engine.buildSearchRequest(config);',
    'return [{',
    '  json: {',
    '    searchBody,',
    '    sandbox: config.sandboxMode,',
    '    runId: __runId(),',
    '    configWarnings: config.warnings.map(Engine.redact),',
    '  },',
    '}];',
  ].join('\n'),

  evaluate: [
    '// ===== ENTRY: Evaluate SLA & Plan Escalations =====',
    '// Config errors are fatal (fail fast). Data and API errors degrade gracefully into a run_summary item.',
    'const config = Config.loadConfig(__readEnv());',
    'const runId = __runId();',
    'try {',
    '  const inputItems = $input.all();',
    '  if (!Array.isArray(inputItems) || inputItems.length === 0) {',
    "    return [{ json: { kind: 'run_summary', status: 'NO_INPUT', sandbox: config.sandboxMode, runId, telemetry: null } }];",
    '  }',
    '  const fetched = Engine.extractTicketsFromResponses(inputItems);',
    '  const result = Engine.processTickets(fetched.tickets, config, new Date(), { runId, fetchErrors: fetched.errors });',
    '  const items = Engine.toN8nItems(result, config, { runId });',
    "  if (fetched.rateLimited) items[0].json.status = 'PARTIAL_RATE_LIMITED';",
    "  else if (fetched.errors.length > 0) items[0].json.status = fetched.tickets.length > 0 ? 'PARTIAL_FETCH_ERROR' : 'FETCH_ERROR';",
    '  return items;',
    '} catch (err) {',
    '  return [{',
    '    json: {',
    "      kind: 'run_summary',",
    "      status: 'ENGINE_ERROR',",
    '      sandbox: config.sandboxMode,',
    '      runId,',
    '      error: Engine.redact(err && err.message ? err.message : String(err)),',
    '    },',
    '  }];',
    '}',
  ].join('\n'),

  slackBuilder: [
    '// ===== ENTRY: Slack Block Kit Builder =====',
    'const config = Config.loadConfig(__readEnv());',
    'const output = [];',
    'for (const item of $input.all()) {',
    '  const data = (item && item.json) || {};',
    '  const escalations = Array.isArray(data.escalations) ? data.escalations : [];',
    '  if (escalations.length === 0) continue; // nothing to post for this item',
    '  try {',
    '    const message = Engine.buildSlackBlocks(escalations, config, { runId: data.runId });',
    '    output.push({ json: {',
    '      channel: message.channel,',
    '      fallbackText: message.text,',
    '      blocks: message.blocks,',
    '      blocksJson: JSON.stringify({ blocks: message.blocks }),',
    '      ticketIds: escalations.map((e) => e.ticketId),',
    '    } });',
    '  } catch (err) {',
    "    const fallbackText = 'SLA escalation digest could not be rendered. ' + escalations.length + ' ticket(s) need attention; see the n8n execution log.';",
    "    const blocks = [{ type: 'section', text: { type: 'mrkdwn', text: fallbackText } }];",
    '    output.push({ json: {',
    '      channel: config.channels.slackChannel,',
    '      fallbackText,',
    '      blocks,',
    '      blocksJson: JSON.stringify({ blocks }),',
    '      ticketIds: escalations.map((e) => e.ticketId),',
    '      error: Engine.redact(err && err.message ? err.message : String(err)),',
    '    } });',
    '  }',
    '}',
    'return output;',
  ].join('\n'),

  dryRun: [
    '// ===== ENTRY: Dry-Run Telemetry =====',
    '// SANDBOX_MODE=true routes every planned action here instead of to HubSpot, Slack or email.',
    'try {',
    '  const report = Engine.buildDryRunReport($input.all().map((item) => (item && item.json) || {}));',
    '  report.lines.forEach((line) => console.log(line));',
    '  return [{ json: report }];',
    '} catch (err) {',
    "  return [{ json: { kind: 'dry_run_report', status: 'REPORT_ERROR', error: Engine.redact(err && err.message ? err.message : String(err)) } }];",
    '}',
  ].join('\n'),
};

function codeNode(name, entryKey, position, notes) {
  return {
    parameters: { jsCode: `${buildPreamble()}\n${ENTRIES[entryKey]}\n` },
    id: stableId(name),
    name,
    type: 'n8n-nodes-base.code',
    typeVersion: 2,
    position,
    notes,
  };
}

function hubspotHttpNode(name, position, parameters, notes) {
  return Object.assign(
    {
      parameters: Object.assign(
        { authentication: 'predefinedCredentialType', nodeCredentialType: 'hubspotAppToken' },
        parameters
      ),
      id: stableId(name),
      name,
      type: 'n8n-nodes-base.httpRequest',
      typeVersion: 4.2,
      position,
      credentials: CREDENTIALS.hubspot,
      notes,
      onError: 'continueRegularOutput',
    },
    RETRY
  );
}

function switchRule(kind, label) {
  return {
    conditions: {
      options: { caseSensitive: true, leftValue: '', typeValidation: 'strict' },
      conditions: [
        {
          id: stableId(`rule-${kind}`),
          leftValue: '={{ $json.kind }}',
          rightValue: kind,
          operator: { type: 'string', operation: 'equals' },
        },
      ],
      combinator: 'and',
    },
    renameOutput: true,
    outputKey: label,
  };
}

/** Assemble the full n8n workflow object. */
